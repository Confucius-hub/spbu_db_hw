# ===== ТИТУЛЬНЫЙ ЛИСТ =====
def tl(text, bold=False, italic=False, align=WD_ALIGN_PARAGRAPH.CENTER,
       size=14, before=0, after=0, caps=False):
    p = doc.add_paragraph()
    p.alignment = align
    p.paragraph_format.line_spacing_rule = WD_LINE_SPACING.SINGLE
    p.paragraph_format.space_before = Pt(before)
    p.paragraph_format.space_after = Pt(after)
    p.paragraph_format.first_line_indent = Cm(0)
    r = p.add_run(text)
    set_run(r, size=size, bold=bold, italic=italic, caps=caps)
    return p


