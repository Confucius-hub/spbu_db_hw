def H(text, lvl=1):
    p = doc.add_paragraph()
    p.paragraph_format.first_line_indent = Cm(0)
    p.paragraph_format.space_before = Pt(12)
    p.paragraph_format.space_after = Pt(6)
    p.alignment = WD_ALIGN_PARAGRAPH.LEFT
    r = p.add_run(text)
    r.bold = True
    r.font.size = Pt(16 if lvl==1 else 14)
    r.font.name = 'Times New Roman'
    return p

def P(text):
    p = doc.add_paragraph(text)
    return p

def fig(path, caption, width=Cm(16.5)):
    p = doc.add_paragraph(); p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    p.paragraph_format.first_line_indent = Cm(0)
    p.paragraph_format.space_before = Pt(6)
    p.add_run().add_picture(path, width=width)
    c = doc.add_paragraph(); c.alignment = WD_ALIGN_PARAGRAPH.CENTER
    c.paragraph_format.first_line_indent = Cm(0)
    c.paragraph_format.space_after = Pt(10)
    r = c.add_run(caption); r.font.size = Pt(12); r.font.name = 'Times New Roman'

def table(headers, rows, caption, widths=None):
    cap = doc.add_paragraph(); cap.paragraph_format.first_line_indent = Cm(0)
    cap.paragraph_format.space_before = Pt(8)
    r = cap.add_run(caption); r.font.size = Pt(12); r.font.name='Times New Roman'
    t = doc.add_table(rows=1, cols=len(headers))
    t.style = 'Table Grid'; t.alignment = WD_TABLE_ALIGNMENT.CENTER
    hdr = t.rows[0].cells
    for i,h in enumerate(headers):
        hdr[i].paragraphs[0].alignment = WD_ALIGN_PARAGRAPH.CENTER
        run = hdr[i].paragraphs[0].add_run(h); run.bold=True
        run.font.size=Pt(12); run.font.name='Times New Roman'
    for row in rows:
        cells = t.add_row().cells
        for i,v in enumerate(row):
            cells[i].paragraphs[0].alignment = WD_ALIGN_PARAGRAPH.CENTER
            run = cells[i].paragraphs[0].add_run(str(v))
            run.font.size=Pt(12); run.font.name='Times New Roman'
    doc.add_paragraph().paragraph_format.space_after = Pt(4)

