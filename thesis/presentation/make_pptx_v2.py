    slide_titles = {
        1:  'Слайд 1 — Титульный',
        2:  'Слайд 2 — Цель и задачи',
        3:  'Слайд 3 — Актуальность',
        4:  'Слайд 4 — Данные и метод (SAR + датасет)',
        5:  'Слайд 5 — Предобработка: ESA SNAP и QGIS',
        6:  'Слайд 6 — Кейс A: реальные разливы (Кольский + Норильск)',
        7:  'Слайд 7 — Кейс B: ложные цели в действии (Варандей / Печенга / Сабетта)',
        8:  'Слайд 8 — Модель DeepLabV3+',
        9:  'Слайд 9 — Результаты и метрики',
        10: 'Слайд 10 — Научная новизна и сравнение с аналогами',
        11: 'Слайд 11 — Выводы и практическая значимость',
    }

    doc = Document()
    sec = doc.sections[0]
    sec.top_margin = Cm(2.0); sec.bottom_margin = Cm(2.0)
    sec.left_margin = Cm(2.5); sec.right_margin = Cm(1.5)
    style = doc.styles['Normal']
    style.font.name = 'Times New Roman'; style.font.size = DPt(13)
    style.element.rPr.rFonts.set(dqn('w:eastAsia'), 'Times New Roman')

    ph = doc.add_paragraph(); ph.alignment = WD_ALIGN_PARAGRAPH.CENTER
    rr = ph.add_run('Речь к защите магистерской диссертации')
    rr.font.name = 'Times New Roman'; rr.font.size = DPt(15); rr.font.bold = True

    ps = doc.add_paragraph(); ps.alignment = WD_ALIGN_PARAGRAPH.CENTER
    rr = ps.add_run(
        'Детектирование нефтяных разливов в арктических портах по данным Sentinel-1  '
        '·  ≈ 6–7 минут'
    )
    rr.font.name = 'Times New Roman'; rr.font.size = DPt(11); rr.font.italic = True
    doc.add_paragraph()

    for i in range(1, TOTAL + 1):
        ph = doc.add_paragraph()
        ph.paragraph_format.space_before = DPt(8)
        ph.paragraph_format.space_after = DPt(2)
        rr = ph.add_run(slide_titles[i])
        rr.font.name = 'Times New Roman'; rr.font.size = DPt(12); rr.font.bold = True
        rr.font.color.rgb = DRGB(0x1E, 0x3A, 0x5F)
        pb = doc.add_paragraph()
        pb.alignment = WD_ALIGN_PARAGRAPH.JUSTIFY
        pb.paragraph_format.line_spacing = 1.35
        pb.paragraph_format.space_after = DPt(4)
        rr = pb.add_run(SPEECH[i])
        rr.font.name = 'Times New Roman'; rr.font.size = DPt(13)

    doc.save(SPEECH_OUT)
    print(f'Saved → {SPEECH_OUT}')


