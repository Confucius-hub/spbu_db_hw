def fade(slide, speed='med'):
    sld = slide._element
    for ex in sld.findall(qn('p:transition')):
        sld.remove(ex)
    tr = etree.SubElement(sld, qn('p:transition'))
    tr.set('spd', speed)
    etree.SubElement(tr, qn('p:fade'))


def R(s, x, y, w, h, fill, line_col=None, line_w=None):
    sp = s.shapes.add_shape(MSO_SHAPE.RECTANGLE,
                            Inches(x), Inches(y), Inches(w), Inches(h))
    sp.fill.solid()
    sp.fill.fore_color.rgb = fill
    if line_col is None:
        sp.line.fill.background()
    else:
        sp.line.color.rgb = line_col
        sp.line.width = Pt(line_w or 0.75)
    sp.shadow.inherit = False
    return sp


def T(s, x, y, w, h, text='', sz=10, col=GRAY, bold=False, italic=False,
      align=PP_ALIGN.LEFT, anchor=MSO_ANCHOR.TOP, sp_after=0, wrap=True):
    tb = s.shapes.add_textbox(Inches(x), Inches(y), Inches(w), Inches(h))
    tf = tb.text_frame
    tf.word_wrap = wrap
    tf.vertical_anchor = anchor
    for i, line in enumerate(text.split('\n')):
        p = tf.paragraphs[0] if i == 0 else tf.add_paragraph()
        p.alignment = align
        if sp_after:
            p.space_after = Pt(sp_after)
        r = p.add_run()
        r.text = line
        r.font.name = FONT; r.font.size = Pt(sz)
        r.font.bold = bold; r.font.italic = italic; r.font.color.rgb = col
    return tb, tf


def TWO(s, x, y, w, h, bold_text, bold_col, rest_text, rest_col=GRAY,
        sz=9, bg=None):
    """Одна строка: жирный термин + обычное пояснение (один абзац)."""
    tb = s.shapes.add_textbox(Inches(x), Inches(y), Inches(w), Inches(h))
    tf = tb.text_frame; tf.word_wrap = True
    p = tf.paragraphs[0]
    r1 = p.add_run(); r1.text = bold_text + '  '
    r1.font.name = FONT; r1.font.size = Pt(sz); r1.font.bold = True
    r1.font.color.rgb = bold_col
    r2 = p.add_run(); r2.text = rest_text
    r2.font.name = FONT; r2.font.size = Pt(sz); r2.font.color.rgb = rest_col
    return tb, tf


def PIC(s, fname, x, y, max_w, max_h, center=True):
    path = os.path.join(FIGS, fname)
    iw, ih = Image.open(path).size
    ar = iw / ih
    bx = max_w / max_h
    if ar > bx:
        w = max_w; h = max_w / ar
    else:
        h = max_h; w = max_h * ar
    ox = (max_w - w) / 2 if center else 0
    oy = (max_h - h) / 2 if center else 0
    s.shapes.add_picture(path, Inches(x + ox), Inches(y + oy),
                         Inches(w), Inches(h))


