def main():
    doc = Document()
    sec = doc.sections[0]
    sec.top_margin = Cm(2.0); sec.bottom_margin = Cm(2.0)
    sec.left_margin = Cm(2.5); sec.right_margin = Cm(1.5)
    style = doc.styles['Normal']
    style.font.name = 'Times New Roman'; style.font.size = Pt(13)
    style.element.rPr.rFonts.set(qn('w:eastAsia'), 'Times New Roman')

    h = doc.add_paragraph(); h.alignment = WD_ALIGN_PARAGRAPH.CENTER
    r = h.add_run('Вопросы комиссии и ответы — подготовка к защите')
    r.font.name = 'Times New Roman'; r.font.size = Pt(15); r.font.bold = True

    sub = doc.add_paragraph(); sub.alignment = WD_ALIGN_PARAGRAPH.CENTER
    r = sub.add_run('Детектирование нефтяных разливов в арктических портах · Sentinel-1')
    r.font.name = 'Times New Roman'; r.font.size = Pt(11); r.font.italic = True
    doc.add_paragraph()

    for i, (q, a) in enumerate(QA, 1):
        pq = doc.add_paragraph()
        pq.paragraph_format.space_before = Pt(8)
        pq.paragraph_format.space_after = Pt(2)
        rr = pq.add_run(f'{i}. {q}')
        rr.font.name = 'Times New Roman'; rr.font.size = Pt(12.5); rr.font.bold = True
        rr.font.color.rgb = NAVY

        pa = doc.add_paragraph()
        pa.alignment = WD_ALIGN_PARAGRAPH.JUSTIFY
        pa.paragraph_format.line_spacing = 1.3
        pa.paragraph_format.space_after = Pt(4)
        ra = pa.add_run('Ответ: ')
        ra.font.name = 'Times New Roman'; ra.font.size = Pt(13); ra.font.bold = True
        ra.font.color.rgb = GREEN
        rb = pa.add_run(a)
        rb.font.name = 'Times New Roman'; rb.font.size = Pt(13)

    doc.save(OUT)
    print(f'Saved → {OUT}  ({len(QA)} questions)')


if __name__ == '__main__':
    main()
