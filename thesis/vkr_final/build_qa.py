# -*- coding: utf-8 -*-
"""Потенциальные вопросы ГЭК и готовые ответы к защите ВКР Байханова В. К."""
from docx import Document
from docx.shared import Pt, Mm, RGBColor
from docx.enum.text import WD_ALIGN_PARAGRAPH, WD_LINE_SPACING
from docx.oxml.ns import qn

doc = Document()
st = doc.styles["Normal"]
st.font.name = "Times New Roman"
st.font.size = Pt(13)
st.element.rPr.rFonts.set(qn("w:eastAsia"), "Times New Roman")
st.paragraph_format.line_spacing_rule = WD_LINE_SPACING.ONE_POINT_FIVE
for s in doc.sections:
    s.left_margin = Mm(22); s.right_margin = Mm(15)
    s.top_margin = Mm(18); s.bottom_margin = Mm(18)

BLUE = RGBColor(0x1E, 0x40, 0xAF)


def title(t, sub):
    p = doc.add_paragraph(); p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    r = p.add_run(t); r.bold = True; r.font.size = Pt(16)
    p2 = doc.add_paragraph(); p2.alignment = WD_ALIGN_PARAGRAPH.CENTER
    r2 = p2.add_run(sub); r2.italic = True; r2.font.size = Pt(11)
    r2.font.color.rgb = RGBColor(0x6B, 0x72, 0x80)
    p2.paragraph_format.space_after = Pt(8)


def section(t):
    p = doc.add_paragraph()
    r = p.add_run(t); r.bold = True; r.font.size = Pt(14); r.font.color.rgb = BLUE
    p.paragraph_format.space_before = Pt(12); p.paragraph_format.space_after = Pt(4)


def qa(n, q, a):
    pq = doc.add_paragraph()
    pq.paragraph_format.space_after = Pt(2)
    rq = pq.add_run(f"В{n}. {q}")
    rq.bold = True; rq.font.size = Pt(13)
    pa = doc.add_paragraph()
    pa.alignment = WD_ALIGN_PARAGRAPH.JUSTIFY
    pa.paragraph_format.space_after = Pt(8)
    pa.paragraph_format.left_indent = Mm(6)
    ra = pa.add_run("Ответ. ")
    ra.bold = True; ra.italic = True
    pa.add_run(a)


title("Вопросы ГЭК и ответы к защите ВКР",
      "Автоматическое детектирование нефтяных разливов в арктических портах "
      "по данным Sentinel-1 · Байханов В. К. · СПбГУ · 2026")

# ── A. Архитектура и модель ──────────────────────────────────────────────────
section("A. Архитектура и выбор модели")
qa(1, "Почему DeepLabV3+, а не U-Net или трансформер (SegFormer)?",
   "DeepLabV3+ сочетает ASPP-модуль, который захватывает контекст пятна сразу в "
   "нескольких масштабах, и декодер, восстанавливающий чёткие границы. Это "
   "критично для нефтяных пятен разного размера и формы. U-Net я использовал как "
   "базовую модель сравнения — DeepLabV3+ дал выше F1. Трансформеры (SegFormer) "
   "требуют существенно больше данных, что при ограниченном арктическом наборе "
   "привело бы к переобучению.")
qa(2, "Что такое блоки внимания scSE и какой от них эффект?",
   "scSE — это spatial и channel Squeeze-and-Excitation: модуль внимания, который "
   "усиливает информативные каналы признаков и важные пространственные зоны "
   "снимка. На SAR-данных он помогает модели концентрироваться на тёмных "
   "аномалиях и подавлять спекл-шум. В абляции добавление scSE дало прирост "
   "F1 порядка двух–трёх сотых.")
qa(3, "Почему лёд и сушу объединили в один класс, а не разделили?",
   "Цель работы — детектировать нефть, а не картировать лёд. И лёд, и суша на "
   "SAR выступают как «не-вода и не-нефть», и их смешение между собой не вредит "
   "основной задаче. Объединение упрощает разметку и снижает дисбаланс. При "
   "необходимости класс легко разделить — архитектура это позволяет.")
qa(4, "Почему именно ResNet-50, а не более глубокая или лёгкая сеть?",
   "ResNet-50 — компромисс между качеством и скоростью: достаточно глубокий для "
   "сложных признаков, но не переобучается на нашем объёме данных и укладывается "
   "в память RTX 3090. Предобучение на ImageNet ускорило сходимость даже при "
   "переходе к одноканальному радарному входу.")

# ── B. Данные и разметка ─────────────────────────────────────────────────────
section("B. Данные, разметка и обучение")
qa(5, "Всего 13 собственных сцен Кольского залива — этого достаточно?",
   "13 сцен — это арктическое подмножество для дообучения и тестирования; "
   "основной объём (1112 сцен) даёт открытый набор MKLab Krestenitis. После "
   "нарезки на тайлы 256×256 и аугментаций эффективный объём вырос до 4128 "
   "фрагментов. Тестовая выборка из 412 тайлов статистически репрезентативна, а "
   "результат F1 = 0,89 это подтверждает.")
qa(6, "Как боролись с переобучением при малом своём наборе?",
   "Использовал аугментации (повороты, отражения, TTA ×4), регуляризацию через "
   "weight decay, раннюю остановку по валидационному mIoU и деление на уровне "
   "сцен, а не тайлов — чтобы фрагменты одной сцены не попадали одновременно в "
   "train и test. Кривые обучения и валидации идут близко, признаков "
   "переобучения нет.")
qa(7, "Как вы уверены, что размеченное пятно — нефть, а не look-alike?",
   "Разметка верифицирована по двум независимым источникам: данным реанализа "
   "ERA5 (скорость ветра — при штиле растёт риск ложных плёнок) и судовым данным "
   "AIS (наличие судна рядом по времени и месту). Для Кольского залива "
   "опорным служил подтверждённый разлив мазута 11 августа 2024 года.")
qa(8, "Почему деление 70/20/10 именно на уровне сцен, а не тайлов?",
   "Тайлы одной сцены сильно скоррелированы. Если делить по тайлам, фрагменты "
   "одной сцены попадут и в обучение, и в тест — это завысит метрики (утечка "
   "данных). Деление по сценам даёт честную оценку обобщающей способности.")

# ── C. Функция потерь и дисбаланс ────────────────────────────────────────────
section("C. Функция потерь и дисбаланс классов")
qa(9, "Почему вес класса «нефть» именно 9,8? Как подобрали?",
   "Вес подбирался обратно пропорционально частоте класса и уточнялся по "
   "сетке на валидации по F1 класса «нефть». Значение 9,8 дало наилучший баланс "
   "между полнотой и точностью; при бо́льших весах росли ложные срабатывания, при "
   "меньших — пропуски нефти.")
qa(10, "Почему Dice-BCE, а не Focal Loss или Tversky?",
   "BCE обеспечивает стабильный попиксельный градиент, а Dice напрямую "
   "оптимизирует перекрытие масок и устойчив к дисбалансу. Их комбинация дала "
   "лучший результат, чем каждая по отдельности. Focal Loss пробовал — выигрыша "
   "над взвешенной Dice-BCE он не дал.")
qa(11, "Что такое дисбаланс классов и почему это проблема?",
   "Пиксели нефти составляют менее 2,4 % набора. Без коррекции модель достигает "
   "высокой accuracy, просто предсказывая «не нефть» везде, но при этом "
   "пропускает сами разливы. Поэтому я и ввёл весовые коэффициенты и метрику F1, "
   "нечувствительную к преобладанию фона.")

# ── D. Результаты и метрики ──────────────────────────────────────────────────
section("D. Результаты и метрики")
qa(12, "Почему основная метрика — F1, а не общая точность (accuracy)?",
   "При сильном дисбалансе accuracy неинформативна: 95 % можно получить, вообще "
   "не находя нефть. F1 — гармоническое среднее точности и полноты именно по "
   "классу «нефть» — честно отражает качество детектирования редкого класса.")
qa(13, "8,4 % нефти уходит в класс «лёд + суша» — это много? Как улучшить?",
   "Это основной тип ошибки, и он физически объясним: молодой лёд и нефть дают "
   "схожие тёмные сигнатуры обратного рассеяния. Снизить ошибку можно "
   "привлечением второй поляризации (VH), временны́х рядов и целевым дообучением "
   "на ледовых сценах — это направление дальнейшей работы.")
qa(14, "Насколько результат устойчив, не случаен ли F1 = 0,89?",
   "Оценка получена на независимой тестовой выборке из 412 тайлов, не "
   "участвовавших в обучении. Метрики по всем трём классам согласованы (вода и "
   "лёд+суша около 96 %), а кривые обучения стабильны — результат "
   "воспроизводим, а не случайный выброс.")

# ── E. Переносимость и практика ──────────────────────────────────────────────
section("E. Переносимость и практическое применение")
qa(15, "Почему качество падает на Сабетте до 0,76?",
   "Сабетта — самая сложная акватория: жировой и ниласовый лёд, припай — "
   "ледовые типы, слабо представленные в обучающих данных. Это закономерное "
   "снижение при переносе без дообучения. После целевого дообучения на местных "
   "сценах качество восстанавливается.")
qa(16, "Как это применить в реальной системе мониторинга?",
   "Конвейер модульный и работает на стандартных сценах Sentinel-1, обработка "
   "одной сцены — 65 секунд. Его можно встроить в автоматический пайплайн: "
   "загрузка снимка из открытого архива Copernicus → предобработка → "
   "сегментация → верификация по ERA5 и AIS → оповещение оператора. Код открыт.")
qa(17, "Чем работа отличается от уже существующих систем детектирования?",
   "Существующие подходы бинарные («нефть — фон») и не выделяют лёд, давая до "
   "70 % ложных тревог в Арктике. Ключевое отличие — трёхклассовая схема с "
   "явным классом «лёд + суша» и верификация по метео- и судовым данным, что "
   "прицельно снижает арктические ложные срабатывания.")

# ── F. Новизна и общие ───────────────────────────────────────────────────────
section("F. Новизна и общие вопросы")
