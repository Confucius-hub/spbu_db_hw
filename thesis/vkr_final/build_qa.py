GREEN = RGBColor(0x06, 0x60, 0x27)


def title_doc(t, sub):
    p = doc.add_paragraph(); p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    r = p.add_run(t); r.bold = True; r.font.size = Pt(16)
    p2 = doc.add_paragraph(); p2.alignment = WD_ALIGN_PARAGRAPH.CENTER
    r2 = p2.add_run(sub); r2.italic = True; r2.font.size = Pt(11)
    r2.font.color.rgb = RGBColor(0x6B, 0x72, 0x80)
    p2.paragraph_format.space_after = Pt(8)


def part_heading(t):
    p = doc.add_paragraph()
    r = p.add_run(t); r.bold = True; r.font.size = Pt(15)
    r.font.color.rgb = GREEN
    p.paragraph_format.space_before = Pt(14)
    p.paragraph_format.space_after = Pt(6)


def section(t):
    p = doc.add_paragraph()
    r = p.add_run(t); r.bold = True; r.font.size = Pt(14); r.font.color.rgb = BLUE
    p.paragraph_format.space_before = Pt(12); p.paragraph_format.space_after = Pt(4)


def slide_qa(n, slide_title, q, a):
    """Per-slide entry: slide number + title as header, then Q→A."""
    ph = doc.add_paragraph()
    ph.paragraph_format.space_after = Pt(2)
    rh = ph.add_run(f"Слайд {n}. {slide_title}")
    rh.bold = True; rh.font.size = Pt(13); rh.font.color.rgb = BLUE

    pq = doc.add_paragraph()
    pq.paragraph_format.space_after = Pt(2)
    pq.paragraph_format.left_indent = Mm(4)
    rq = pq.add_run(f"Вероятный вопрос: {q}")
    rq.bold = True; rq.italic = True; rq.font.size = Pt(12)

    pa = doc.add_paragraph()
    pa.alignment = WD_ALIGN_PARAGRAPH.JUSTIFY
    pa.paragraph_format.space_after = Pt(10)
    pa.paragraph_format.left_indent = Mm(8)
    ra = pa.add_run("Ответ. ")
    ra.bold = True; ra.italic = True
    pa.add_run(a)


def qa(n, q, a):
    pq = doc.add_paragraph()
    pq.paragraph_format.space_after = Pt(2)
    rq = pq.add_run(f"В{n}. {q}")
    rq.bold = True; rq.font.size = Pt(13)
    pa = doc.add_paragraph()
    pa.alignment = WD_ALIGN_PARAGRAPH.JUSTIFY
    pa.paragraph_format.space_after = Pt(8)
    pa.paragraph_format.left_indent = Mm(6)
    ra = pa.add_run("Ответ. ")
    ra.bold = True; ra.italic = True
    pa.add_run(a)


