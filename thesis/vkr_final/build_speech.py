def H(t):
    p = doc.add_paragraph()
    r = p.add_run(t); r.bold = True; r.font.size = Pt(13)
    r.font.color.rgb = None
    p.paragraph_format.space_before = Pt(10); p.paragraph_format.space_after = Pt(2)


