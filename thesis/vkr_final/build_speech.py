from docx import Document
from docx.shared import Pt, Mm, RGBColor
from docx.enum.text import WD_ALIGN_PARAGRAPH, WD_LINE_SPACING
from docx.oxml.ns import qn

doc = Document()
st = doc.styles["Normal"]
st.font.name = "Times New Roman"
st.font.size = Pt(14)
st.element.rPr.rFonts.set(qn("w:eastAsia"), "Times New Roman")
st.paragraph_format.line_spacing_rule = WD_LINE_SPACING.ONE_POINT_FIVE
for sec in doc.sections:
    sec.left_margin = Mm(25); sec.right_margin = Mm(15)
    sec.top_margin = Mm(20); sec.bottom_margin = Mm(20)

BLUE = RGBColor(0x1E, 0x40, 0xAF)
RED  = RGBColor(0xB5, 0x33, 0x1F)

def title_block(t, sub):
    p = doc.add_paragraph(); p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    r = p.add_run(t); r.bold = True; r.font.size = Pt(15)
    p2 = doc.add_paragraph(); p2.alignment = WD_ALIGN_PARAGRAPH.CENTER
    r2 = p2.add_run(sub); r2.italic = True; r2.font.size = Pt(11)
    r2.font.color.rgb = RGBColor(0x6B, 0x72, 0x80)
    p2.paragraph_format.space_after = Pt(10)

def slide_head(n, title, timing):
    p = doc.add_paragraph()
    p.paragraph_format.space_before = Pt(12); p.paragraph_format.space_after = Pt(2)
    r1 = p.add_run(f"СЛАЙД {n}. {title.upper()}")
    r1.bold = True; r1.font.size = Pt(12); r1.font.color.rgb = BLUE
    r2 = p.add_run(f"  [{timing}]")
    r2.font.size = Pt(10); r2.font.color.rgb = RGBColor(0x6B, 0x72, 0x80)
    r2.italic = True

def transition(bridge, nav):
    """bridge — фраза-связка, которую проговаривают; nav — куда переключить слайд."""
    p = doc.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.JUSTIFY
    p.paragraph_format.first_line_indent = Mm(10)
    p.paragraph_format.space_before = Pt(4); p.paragraph_format.space_after = Pt(2)
    r = p.add_run(bridge)
    r.italic = True; r.font.size = Pt(13); r.font.color.rgb = RED
    p2 = doc.add_paragraph()
    p2.paragraph_format.space_before = Pt(0); p2.paragraph_format.space_after = Pt(2)
    r2 = p2.add_run(f"[Перелистнуть → {nav}]")
    r2.font.size = Pt(10); r2.font.color.rgb = RGBColor(0x6B, 0x72, 0x80)

def P(t):
    p = doc.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.JUSTIFY
    p.paragraph_format.first_line_indent = Mm(10)
    p.paragraph_format.space_after = Pt(4)
    p.add_run(t)

